import sharp from 'sharp';
import { format, resolveConfig } from 'prettier';
import { readdir, mkdir, writeFile } from 'node:fs/promises';
import { basename, join } from 'node:path';

const directory = 'src/portfolio/screenshots';
const output = join(directory, 'optimized');
await mkdir(output, { recursive: true });
const files = (await readdir(directory))
  .filter((file) => file.endsWith('.jpg'))
  .sort();
const imports = [];
const entries = [];
for (const [index, file] of files.entries()) {
  const input = join(directory, file);
  const { width } = await sharp(input).metadata();
  const widths = [
    ...new Set([640, 1100, width].filter((size) => size <= width)),
  ].sort((a, b) => a - b);
  const variants = [];
  for (const size of widths) {
    const name = `${basename(file, '.jpg')}-${size}.webp`;
    await sharp(input)
      .resize({ width: size, withoutEnlargement: true })
      .webp({ quality: 85, effort: 6 })
      .toFile(join(output, name));
    const variable = `image${index}_${size}`;
    imports.push(`import ${variable} from './screenshots/optimized/${name}';`);
    variants.push(`{ src: ${variable}, width: ${size} }`);
  }
  entries.push(`${JSON.stringify(file)}: [${variants.join(', ')}]`);
}
await writeFile(
  'src/portfolio/screenshotSources.ts',
  await format(
    `${imports.join('\n')}\n\n// Generated by npm run images:generate; retain JPEGs as source originals.\nexport const screenshotSources = {\n${entries.join(',\n')}\n};\n`,
    {
      ...(await resolveConfig('src/portfolio/screenshotSources.ts')),
      parser: 'typescript',
    },
  ),
);
